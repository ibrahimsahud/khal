function computeSummary() {
  const balances = {
    USD: 0,
    TRY: 0,
    SYP_NEW: 0,
    SYP_OLD: 0
  };

  let totalIn = 0;
  let totalOut = 0;

  state.operations.forEach(function (operation) {
    const amountIn = toNumber(operation.amount_in);
    const amountOut = toNumber(operation.amount_out);

    if (balances[operation.currency_in] != null) {
      balances[operation.currency_in] += amountIn;
    }

    if (balances[operation.currency_out] != null) {
      balances[operation.currency_out] -= amountOut;
    }

    totalIn += amountIn;
    totalOut += amountOut;
  });

  const usdTry = state.rates.usdTry;
  const usdSypNew = state.rates.usdSypNew;
  const usdSypOld = state.rates.usdSypOld;

  const tryCostUsd = usdTry ? balances.TRY / usdTry : 0;
  const sypNewCostUsd = usdSypNew ? balances.SYP_NEW / usdSypNew : 0;
  const sypOldCostUsd = usdSypOld ? balances.SYP_OLD / usdSypOld : 0;

  const netUSD = balances.USD + tryCostUsd + sypNewCostUsd + sypOldCostUsd;
  const netTRY = netUSD * usdTry;
  const netSYP = netUSD * usdSypNew;

  return {
    balanceUSD: balances.USD,
    balanceTRY: balances.TRY,
    balanceSypNew: balances.SYP_NEW,
    balanceSypOld: balances.SYP_OLD,
    totalIn: totalIn,
    totalOut: totalOut,
    netUSD: netUSD,
    netTRY: netTRY,
    netSYP: netSYP,
    netTryCostUsd: tryCostUsd,
    netSypCostUsd: sypNewCostUsd + sypOldCostUsd
  };
}

