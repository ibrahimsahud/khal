async function fetchRates() {
  const response = await supabaseClient
    .from("rates")
    .select("id, usd_try, usd_syp_new, usd_syp_old")
    .eq("id", RATES_ROW_ID)
    .maybeSingle();

  if (response.error) {
    throw response.error;
  }

  if (!response.data) {
    const seed = await supabaseClient.from("rates").upsert({
      id: RATES_ROW_ID,
      usd_try: 0,
      usd_syp_new: 0,
      usd_syp_old: 0
    }).select("id, usd_try, usd_syp_new, usd_syp_old").single();

    if (seed.error) {
      throw seed.error;
    }

    response.data = seed.data;
  }

  state.rates = {
    usdTry: toPositiveNumber(response.data.usd_try),
    usdSypNew: toPositiveNumber(response.data.usd_syp_new),
    usdSypOld: toPositiveNumber(response.data.usd_syp_old)
  };
}

async function fetchTransactions() {
  const response = await supabaseClient
    .from("transactions")
    .select("id, created_at, type, currency_in, amount_in, currency_out, amount_out, rate, notes")
    .order("created_at", { ascending: false });

  if (response.error) {
    throw response.error;
  }

  state.operations = Array.isArray(response.data) ? response.data : [];
}

async function loadDashboardData(showMessage) {
  if (!supabaseReady) {
    updateConnectionBadge("أدخل مفاتيح Supabase");
    showStatus("عدّل SUPABASE_URL و SUPABASE_ANON_KEY داخل app.js أولاً.", true);
    renderStats();
    renderOperationsTable();
    return;
  }

  updateConnectionBadge("جاري المزامنة...");
  setButtonsDisabled(true);

  try {
    await Promise.all([fetchRates(), fetchTransactions()]);
    renderAll();
    updateConnectionBadge("متصل بقاعدة البيانات");
    if (showMessage) {
      showStatus("تم تحديث البيانات من Supabase.");
    }
  } catch (error) {
    updateConnectionBadge("فشل الاتصال");
    showStatus("تعذر جلب البيانات من Supabase: " + (error.message || error), true);
  } finally {
    setButtonsDisabled(false);
  }
}

async function saveRates() {
  if (!supabaseReady) {
    showStatus("لا يمكن حفظ الأسعار قبل إعداد Supabase.", true);
    return;
  }

  const rates = getRatesFromForm();
  setButtonsDisabled(true);

  try {
    const response = await supabaseClient.from("rates").upsert({
      id: RATES_ROW_ID,
      usd_try: rates.usdTry,
      usd_syp_new: rates.usdSypNew,
      usd_syp_old: rates.usdSypOld
    });

    if (response.error) {
      throw response.error;
    }

    state.rates = rates;
    renderAll();
    showStatus("تم تحديث أسعار الصرف بنجاح.");
  } catch (error) {
    showStatus("تعذر حفظ الأسعار: " + (error.message || error), true);
  } finally {
    setButtonsDisabled(false);
  }
}

async function saveOperation() {
  if (!supabaseReady) {
    showStatus("لا يمكن حفظ العملية قبل إعداد Supabase.", true);
    return;
  }

  const operation = getOperationFromForm();

  if (!operation.amount_in && !operation.amount_out) {
    showStatus("أدخل مبلغاً داخلاً أو خارجاً على الأقل.", true);
    return;
  }

  if (operation.currency_in === operation.currency_out && operation.amount_in && operation.amount_out) {
    showStatus("العملة الداخلة والخارجة متطابقتان. راجع العملية قبل الحفظ.", true);
    return;
  }

  setButtonsDisabled(true);

  try {
    const response = await supabaseClient
      .from("transactions")
      .insert(operation)
      .select("id, created_at, type, currency_in, amount_in, currency_out, amount_out, rate, notes")
      .single();

    if (response.error) {
      throw response.error;
    }

    state.operations.unshift(response.data);
    clearOperationForm();
    renderAll();
    showStatus("تم حفظ العملية وتحديث الجدول والإحصائيات مباشرة.");
  } catch (error) {
    showStatus("تعذر حفظ العملية: " + (error.message || error), true);
  } finally {
    setButtonsDisabled(false);
  }
}

function exportCsv() {
  if (!state.operations.length) {
    showStatus("لا توجد عمليات لتصديرها.", true);
    return;
  }

  const headers = [
    "التاريخ",
    "نوع العملية",
    "العملة الداخلة",
    "المبلغ الداخل",
    "العملة الخارجة",
    "المبلغ الخارج",
    "سعر الصرف",
    "الملاحظات"
  ];

  const rows = state.operations.map(function (operation) {
    return [
      formatDate(operation.created_at),
      operation.type,
      operation.currency_in,
      operation.amount_in,
      operation.currency_out,
      operation.amount_out,
      operation.rate,
      operation.notes || ""
    ];
  });

  const csvContent = [headers].concat(rows).map(function (row) {
    return row.map(function (cell) {
      return '"' + String(cell == null ? "" : cell).replace(/"/g, '""') + '"';
    }).join(",");
  }).join("\n");

  const blob = new Blob(["\uFEFF", csvContent], { type: "text/csv;charset=utf-8;" });
  const url = URL.createObjectURL(blob);
  const link = document.createElement("a");
  link.href = url;
  link.download = "transactions.csv";
  document.body.appendChild(link);
  link.click();
  link.remove();
  URL.revokeObjectURL(url);
  showStatus("تم تصدير ملف CSV بنجاح.");
}

